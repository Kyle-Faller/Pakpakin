    public static boolean supports(char c) {
        return c >= 32 && c - 32 < GLYPHS.length;
    }

    /** Width in pixels of the text when each font pixel is drawn ps x ps. */
    public static int width(String text, int ps) {
        return text.isEmpty() ? 0 : text.length() * 6 * ps - ps;   // 5 columns + 1 gap per character
    }

    public static int height(int ps) {
        return GLYPH_H * ps;
    }

    /** Draws the text with its top-left corner at (x, y). */
    public static void draw(Graphics2D g, String text, int x, int y, int ps, Color color) {
        g.setColor(color);
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (supports(c)) {
                int[] cols = GLYPHS[c - 32];
                for (int col = 0; col < GLYPH_W; col++) {
                    for (int row = 0; row < GLYPH_H; row++) {
                        if ((cols[col] >> row & 1) != 0) {
                            g.fillRect(x + col * ps, y + row * ps, ps, ps);
                        }
                    }
                }
            }
            x += 6 * ps;
        }
    }

    /** Draws the text with a drop shadow (offset by shadowPx pixels down and right). */
    public static void drawShadowed(Graphics2D g, String text, int x, int y, int ps,
                                    Color color, Color shadow, int shadowPx) {
        draw(g, text, x + shadowPx, y + shadowPx, ps, shadow);
        draw(g, text, x, y, ps, color);
    }
